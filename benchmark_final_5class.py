import csv
import json
import os
from pathlib import Path

os.environ["TF_CPP_MIN_LOG_LEVEL"] = "2"

import matplotlib.pyplot as plt
import numpy as np
import tensorflow as tf
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
)

from emotion_detector_5class import TemporalAttention
from emotion_logic import (
    apply_adapter_if_confident,
    merge_v1_to_5,
    normalize_probs,
)


BASE_DIR = Path(__file__).resolve().parent

TEST_DIR = BASE_DIR / "data" / "lstm_features" / "test"
MODEL_DIR = BASE_DIR / "models"
RESULT_DIR = BASE_DIR / "results" / "final_5class"

TEMPORAL_MODEL_PATH = MODEL_DIR / "lstm_attention_v1_best.keras"
MEAN_PATH = MODEL_DIR / "lstm_v1_feature_mean.npy"
STD_PATH = MODEL_DIR / "lstm_v1_feature_std.npy"
V1_CLASS_PATH = MODEL_DIR / "lstm_attention_v1_classes.json"
ADAPTER_MODEL_PATH = MODEL_DIR / "sad_neutral_adapter.keras"
ADAPTER_CLASS_PATH = MODEL_DIR / "sad_neutral_adapter_classes.json"

SEQUENCE_LENGTH = 20
FEATURE_DIM = 256
BATCH_SIZE = 32

ADAPTER_CONFIDENCE_THRESHOLD = 0.70
ADAPTER_MIN_GROUP_MASS = 0.15

DEFAULT_V1_CLASSES = [
    "angry",
    "disgust",
    "fear",
    "happy",
    "neutral",
    "sad",
    "surprise",
]

FINAL_CLASSES = [
    "angry",
    "happy",
    "surprise",
    "sad",
    "neutral",
]

DEFAULT_ADAPTER_CLASSES = [
    "neutral",
    "sad",
]

TRUE_LABEL_MAP = {
    "angry": "angry",
    "happy": "happy",
    "fear": "surprise",
    "surprise": "surprise",
    "disgust": "sad",
    "sad": "sad",
    "neutral": "neutral",
}


def load_classes(path, default_classes):
    if not path.is_file():
        return list(default_classes)

    with path.open("r", encoding="utf-8") as file:
        data = json.load(file)

    if isinstance(data, list):
        return [str(item).lower() for item in data]

    if isinstance(data, dict) and "classes" in data:
        return [str(item).lower() for item in data["classes"]]

    raise ValueError(f"Unsupported class metadata in {path}")


def check_required_files():
    required = [
        TEMPORAL_MODEL_PATH,
        MEAN_PATH,
        STD_PATH,
        ADAPTER_MODEL_PATH,
    ]

    missing = [
        str(path)
        for path in required
        if not path.is_file()
    ]

    if missing:
        raise FileNotFoundError(
            "Missing required model artifacts:\n"
            + "\n".join(missing)
        )

    if not TEST_DIR.is_dir():
        raise FileNotFoundError(
            "Missing held-out feature directory:\n"
            f"{TEST_DIR}\n\n"
            "Expected actor-wise test features generated by "
            "extract_lstm_features.py."
        )


def load_test_split(v1_classes):
    x_data = []
    y_original = []
    y_final = []
    sample_names = []

    for original_class in v1_classes:
        class_dir = TEST_DIR / original_class

        if not class_dir.is_dir():
            raise FileNotFoundError(
                f"Missing test class directory: {class_dir}"
            )

        files = sorted(class_dir.glob("*.npy"))

        for path in files:
            features = np.load(path)

            if features.shape != (
                SEQUENCE_LENGTH,
                FEATURE_DIM,
            ):
                raise ValueError(
                    f"Invalid feature shape {features.shape}: {path}"
                )

            x_data.append(
                features.astype(np.float32)
            )
            y_original.append(original_class)
            y_final.append(
                TRUE_LABEL_MAP[original_class]
            )
            sample_names.append(path.name)

    if not x_data:
        raise RuntimeError(
            f"No test feature files found under {TEST_DIR}"
        )

    return (
        np.asarray(x_data, dtype=np.float32),
        y_original,
        y_final,
        sample_names,
    )


def save_confusion_matrix(matrix, labels, title, output_path):
    plt.figure(figsize=(8, 7))
    plt.imshow(matrix)
    plt.title(title)
    plt.xlabel("Predicted")
    plt.ylabel("Actual")
    plt.xticks(
        range(len(labels)),
        labels,
        rotation=45,
        ha="right",
    )
    plt.yticks(
        range(len(labels)),
        labels,
    )

    for row in range(matrix.shape[0]):
        for col in range(matrix.shape[1]):
            plt.text(
                col,
                row,
                str(matrix[row, col]),
                ha="center",
                va="center",
            )

    plt.tight_layout()
    plt.savefig(output_path, dpi=200)
    plt.close()


def evaluate_mode(y_true, y_pred, mode_name):
    accuracy = accuracy_score(
        y_true,
        y_pred,
    )

    macro_f1 = f1_score(
        y_true,
        y_pred,
        labels=FINAL_CLASSES,
        average="macro",
        zero_division=0,
    )

    weighted_f1 = f1_score(
        y_true,
        y_pred,
        labels=FINAL_CLASSES,
        average="weighted",
        zero_division=0,
    )

    report_text = classification_report(
        y_true,
        y_pred,
        labels=FINAL_CLASSES,
        target_names=FINAL_CLASSES,
        zero_division=0,
    )

    report_dict = classification_report(
        y_true,
        y_pred,
        labels=FINAL_CLASSES,
        target_names=FINAL_CLASSES,
        zero_division=0,
        output_dict=True,
    )

    matrix = confusion_matrix(
        y_true,
        y_pred,
        labels=FINAL_CLASSES,
    )

    safe_name = mode_name.lower().replace(" ", "_")

    report_path = (
        RESULT_DIR
        / f"{safe_name}_report.txt"
    )

    with report_path.open(
        "w",
        encoding="utf-8",
    ) as file:
        file.write(
            f"Accuracy: {accuracy:.6f}\n"
        )
        file.write(
            f"Macro F1: {macro_f1:.6f}\n"
        )
        file.write(
            f"Weighted F1: {weighted_f1:.6f}\n\n"
        )
        file.write(report_text)

    save_confusion_matrix(
        matrix,
        FINAL_CLASSES,
        f"Final 5-Class Confusion Matrix — {mode_name}",
        RESULT_DIR / f"{safe_name}_confusion_matrix.png",
    )

    return {
        "accuracy": float(accuracy),
        "macro_f1": float(macro_f1),
        "weighted_f1": float(weighted_f1),
        "classification_report": report_dict,
        "confusion_matrix": matrix.tolist(),
    }


def main():
    check_required_files()
    RESULT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    v1_classes = load_classes(
        V1_CLASS_PATH,
        DEFAULT_V1_CLASSES,
    )

    adapter_classes = load_classes(
        ADAPTER_CLASS_PATH,
        DEFAULT_ADAPTER_CLASSES,
    )

    if set(v1_classes) != set(
        DEFAULT_V1_CLASSES
    ):
        raise ValueError(
            f"Unexpected V1 classes: {v1_classes}"
        )

    if set(adapter_classes) != set(
        DEFAULT_ADAPTER_CLASSES
    ):
        raise ValueError(
            "Sad/Neutral adapter must contain only "
            f"neutral and sad. Found: {adapter_classes}"
        )

    v1_index = {
        name: index
        for index, name in enumerate(
            v1_classes
        )
    }

    (
        x_test,
        y_original,
        y_true,
        sample_names,
    ) = load_test_split(
        v1_classes
    )

    feature_mean = np.load(
        MEAN_PATH
    ).astype(np.float32)

    feature_std = np.load(
        STD_PATH
    ).astype(np.float32)

    feature_std = np.where(
        feature_std < 1e-6,
        1e-6,
        feature_std,
    )

    x_test_normalized = (
        x_test - feature_mean
    ) / feature_std

    temporal_model = (
        tf.keras.models.load_model(
            TEMPORAL_MODEL_PATH,
            custom_objects={
                "TemporalAttention": TemporalAttention,
                "EmotionAI>TemporalAttention": TemporalAttention,
            },
            compile=False,
        )
    )

    adapter_model = (
        tf.keras.models.load_model(
            ADAPTER_MODEL_PATH,
            compile=False,
        )
    )

    base_7_batch = temporal_model.predict(
        x_test_normalized,
        batch_size=BATCH_SIZE,
        verbose=0,
    )

    adapter_batch = adapter_model.predict(
        x_test_normalized,
        batch_size=BATCH_SIZE,
        verbose=0,
    )

    fusion_predictions = []
    adapter_predictions = []
    adapter_active_flags = []
    adapter_confidences = []
    merged_probabilities = []
    adapted_probabilities = []

    for base_7, adapter_probs in zip(
        base_7_batch,
        adapter_batch,
    ):
        base_7 = normalize_probs(
            base_7
        )

        merged_5 = merge_v1_to_5(
            base_7,
            v1_index,
        )

        adapter_probs = normalize_probs(
            adapter_probs
        )

        (
            adapted_5,
            adapter_active,
            _group_mass,
            adapter_confidence,
        ) = apply_adapter_if_confident(
            merged_5=merged_5,
            adapter_probs=adapter_probs,
            adapter_classes=adapter_classes,
            confidence_threshold=(
                ADAPTER_CONFIDENCE_THRESHOLD
            ),
            min_group_mass=(
                ADAPTER_MIN_GROUP_MASS
            ),
            final_classes=FINAL_CLASSES,
        )

        fusion_predictions.append(
            FINAL_CLASSES[
                int(np.argmax(merged_5))
            ]
        )

        adapter_predictions.append(
            FINAL_CLASSES[
                int(np.argmax(adapted_5))
            ]
        )

        adapter_active_flags.append(
            bool(adapter_active)
        )

        adapter_confidences.append(
            float(adapter_confidence)
        )

        merged_probabilities.append(
            merged_5
        )

        adapted_probabilities.append(
            adapted_5
        )

    fusion_metrics = evaluate_mode(
        y_true,
        fusion_predictions,
        "fusion_only",
    )

    adapter_metrics = evaluate_mode(
        y_true,
        adapter_predictions,
        "adapter_assisted",
    )

    activation_count = int(
        sum(adapter_active_flags)
    )

    activation_rate = (
        activation_count
        / len(adapter_active_flags)
    )

    summary = {
        "protocol": {
            "source": (
                "Existing actor-wise RAVDESS test split"
            ),
            "test_actors": "21-24",
            "sample_count": len(y_true),
            "sequence_shape": [
                SEQUENCE_LENGTH,
                FEATURE_DIM,
            ],
            "ground_truth_fusion": {
                "fear": "surprise",
                "disgust": "sad",
            },
            "note": (
                "Actors 21-24 are unseen during training, "
                "but this is not a pristine post-selection test set "
                "because earlier temporal model variants were compared "
                "using the same actor-wise test split."
            ),
            "runtime_smoothing_included": False,
        },
        "fusion_only": fusion_metrics,
        "adapter_assisted": adapter_metrics,
        "adapter": {
            "confidence_threshold": (
                ADAPTER_CONFIDENCE_THRESHOLD
            ),
            "minimum_sad_neutral_group_mass": (
                ADAPTER_MIN_GROUP_MASS
            ),
            "activation_count": activation_count,
            "activation_rate": float(
                activation_rate
            ),
            "mean_adapter_confidence": float(
                np.mean(adapter_confidences)
            ),
            "caveat": (
                "The adapter was trained on a very small private "
                "two-participant webcam dataset. Applying it to "
                "RAVDESS measures cross-domain behavior and does not "
                "make its performance population-level evidence."
            ),
        },
    }

    with (
        RESULT_DIR
        / "final_5class_metrics.json"
    ).open(
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(
            summary,
            file,
            indent=2,
        )

    with (
        RESULT_DIR
        / "predictions.csv"
    ).open(
        "w",
        newline="",
        encoding="utf-8",
    ) as file:
        writer = csv.writer(file)

        writer.writerow(
            [
                "sample",
                "original_label",
                "final_true_label",
                "fusion_only_prediction",
                "adapter_assisted_prediction",
                "adapter_active",
                "adapter_confidence",
            ]
        )

        for row in zip(
            sample_names,
            y_original,
            y_true,
            fusion_predictions,
            adapter_predictions,
            adapter_active_flags,
            adapter_confidences,
        ):
            writer.writerow(row)

    print("")
    print("=" * 72)
    print("FINAL 5-CLASS HELD-OUT BENCHMARK")
    print("=" * 72)
    print(f"Samples: {len(y_true)}")
    print("Actors: 21-24")
    print("")

    print("Fusion only")
    print(
        f"  Accuracy    : "
        f"{fusion_metrics['accuracy']:.4f}"
    )
    print(
        f"  Macro F1    : "
        f"{fusion_metrics['macro_f1']:.4f}"
    )
    print(
        f"  Weighted F1 : "
        f"{fusion_metrics['weighted_f1']:.4f}"
    )
    print("")

    print("Adapter assisted")
    print(
        f"  Accuracy    : "
        f"{adapter_metrics['accuracy']:.4f}"
    )
    print(
        f"  Macro F1    : "
        f"{adapter_metrics['macro_f1']:.4f}"
    )
    print(
        f"  Weighted F1 : "
        f"{adapter_metrics['weighted_f1']:.4f}"
    )
    print("")

    print(
        "Adapter activation: "
        f"{activation_count}/{len(y_true)} "
        f"({activation_rate * 100:.1f}%)"
    )

    print("")
    print(
        "Results saved to:"
    )
    print(
        RESULT_DIR
    )
    print("")
    print(
        "Note: this is a sequence-level benchmark. "
        "Live runtime smoothing across successive webcam "
        "predictions is intentionally not applied."
    )


if __name__ == "__main__":
    main()
